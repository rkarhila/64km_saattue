# Stable internal codes (not localized) used in JSON / RL obs.
UNIT_TYPE_KEY = {0: "panzer", 1: "infantry", 2: "logistics"}
UNIT_TYPE_I18N_KEY = {0: "unit.panzer", 1: "unit.infantry", 2: "unit.logistics"}
TROOP_LETTER_I18N_KEY = {"P": "troop.P", "I": "troop.I", "L": "troop.L", "A": "troop.A"}

_current_lang = DEFAULT_LANG


def set_language(lang: str) -> None:
    global _current_lang
    if lang not in TRANSLATIONS:
        raise ValueError(f"Unsupported language: {lang}")
    _current_lang = lang


def get_language() -> str:
    return _current_lang


def t(key: str, lang: str | None = None) -> str:
    """Translate `key` into the active (or given) language; fall back to key."""
    lang = lang or _current_lang
    table = TRANSLATIONS.get(lang) or TRANSLATIONS[DEFAULT_LANG]
    if key in table:
        return table[key]
    # Fall back to Finnish, then English, then the raw key
    for fallback in (DEFAULT_LANG, "en"):
        if key in TRANSLATIONS.get(fallback, {}):
            return TRANSLATIONS[fallback][key]
    return key


def tf(key: str, **kwargs) -> str:
    """Translate `key` and substitute ``{name}`` placeholders.

    Values are inserted literally, so a card name that contains braces
    cannot break the template.
    """
    text = t(key)
    for name, value in kwargs.items():
        text = text.replace("{" + name + "}", str(value))
    return text


def unit_type_label(unittype: int, lang: str | None = None) -> str:
    return t(UNIT_TYPE_I18N_KEY[unittype], lang=lang)


def troop_label(troop_letter: str, lang: str | None = None) -> str:
    key = TROOP_LETTER_I18N_KEY.get(troop_letter.upper(), "unit.any")
    return t(key, lang=lang)


# Panzer headings are plural; infantry and logistics are singular.
_TROOP_PLURAL = {0: True, 1: False, 2: False}


def format_mauling_target(target: str) -> str:
    """Kohde line for a mauling or ambush target code. Wording is translated."""
    text = (target or "").strip()
    if not text or text == "-":
        return ""
    if all(ch in "ABCE" for ch in text):
        if len(text) == 1:
            return tf("target.all_in_zone", zone=text)
        if len(text) == 2:
            return tf("target.zones_two", a=text[0], b=text[1])
        return tf(
            "target.zones_many",
            listed=", ".join(text[:-1]),
            last=text[-1],
        )

    from .cards import parse_mauling_target

    try:
        sel = parse_mauling_target(text)
    except ValueError:
        return text

    kind = sel["kind"]
    if kind == "none":
        return ""
    if kind == "zone":
        return tf("target.all_in_zone", zone=sel["zone"])
    if kind == "zone_rel":
        rel = int(sel["rel"])
        n = abs(rel)
        ordinal_key = f"target.ordinal.{n}"
        word = t(ordinal_key)
        if word == ordinal_key:
            word = f"{n}."
        side = t("target.side_front" if rel > 0 else "target.side_rear")
        return tf("target.zone_rel", zone=sel["zone"], ordinal=word, side=side)
    if kind == "type":
        unit_type = int(sel["unit_type"])
        noun = unit_type_label(unit_type)
        form = "plural" if _TROOP_PLURAL[unit_type] else "singular"
        head = t(f"target.which.{sel['which']}.{form}")
        if sel["which"] == "second":
            return tf("target.troop_from_front", head=head, noun=noun)
        if sel["which"] == "second_last":
            return tf("target.troop_from_rear", head=head, noun=noun)
        return tf("target.troop_plain", head=head, noun=noun)
    if kind == "atrocity":
        return t(f"target.atrocity.{sel['which']}")
    return text


def _install_phrase_tables() -> None:
    """Merge log and target phrases into the language tables."""
    for lang, table in _PHRASES.items():
        TRANSLATIONS.setdefault(lang, {}).update(table)


